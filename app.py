# --- 핵심 수급 분석 로직 함수 ---
def run_volume_screener(target_list, title_prefix):
    with result_container:
        # 최근 30거래일 이상 데이터 확보 (20일 평균 계산용 + 최근 1개월 탐색)
        start_date = (datetime.now() - timedelta(days=60)).strftime('%Y-%m-%d')
        
        with st.spinner(f"[{title_prefix}] 최근 1달간 거래량 폭증 및 주가 압축 종목을 탐색 중입니다..."):
            results = []
            unique_tickers = list(set(target_list))
            progress_bar = st.progress(0)
            total_items = len(unique_tickers)
            
            for i, code in enumerate(unique_tickers):
                try:
                    df = fdr.DataReader(code, start_date)
                    if len(df) < 25:
                        progress_bar.progress((i + 1) / total_items)
                        continue
                    
                    # 20거래일 평균 거래량 계산 컬럼 추가
                    df['Vol_MA20'] = df['Volume'].rolling(window=20).mean()
                    # 일일 주가 등락률(%) 계산
                    df['Price_Pct'] = df['Close'].pct_change() * 100
                    
                    # 최근 1달(약 20거래일) 동안 조건 충족일이 단 하루라도 있었는지 확인
                    recent_df = df.iloc[-20:]
                    matched_rows = recent_df[
                        (recent_df['Volume'] >= recent_df['Vol_MA20'] * 3.0) & 
                        (recent_df['Price_Pct'].between(-3.0, 3.0))
                    ]
                    
                    if not matched_rows.empty:
                        # 가장 최근에 조건을 충족한 날의 데이터 선택
                        latest_match = matched_rows.iloc[-1]
                        match_date = latest_match.name.strftime('%Y-%m-%d')
                        vol_ratio = latest_match['Volume'] / latest_match['Vol_MA20']
                        price_change = latest_match['Price_Pct']
                        close_price = latest_match['Close']
                        
                        stock_name = NAME_DICT.get(code, code)
                        
                        results.append({
                            '종목코드': code,
                            '종목명': stock_name,
                            '포착일자': match_date,
                            '거래량배율': vol_ratio,
                            '당일등락률': price_change,
                            '종가': close_price
                        })
                except Exception:
                    pass
                progress_bar.progress((i + 1) / total_items)
                
            progress_bar.empty()

        if results:
            df_result = pd.DataFrame(results)
            # 거래량 배율이 높은 순으로 정렬
            df_result = df_result.sort_values(by='거래량배율', ascending=False).reset_index(drop=True)
            
            display_df = df_result.copy()
            display_df['거래량배율'] = display_df['거래량배율'].apply(lambda x: f"{x:.2f}배")
            display_df['당일등락률'] = display_df['당일등락률'].apply(lambda x: f"{x:+.2f}%")
            display_df['종가'] = display_df['종가'].apply(lambda x: f"{x:,.0f}원" if x > 1000 else f"{x:,.2f}")
            
            st.success(f"[{title_prefix}] 분석 완료! 조건(거래량 3배↑ & 등락률 ±3% 이내)을 만족하는 종목 {len(results)}개가 발굴되었습니다.")
            st.dataframe(display_df, use_container_width=True)
            
            # 다운로드 버튼
            txt_content = "종목코드\t종목명\t포착일자\t거래량배율\t당일등락률\t종가\n"
            for _, row in df_result.iterrows():
                txt_content += f"{row['종목코드']}\t{row['종목명']}\t{row['포착일자']}\t{row['거래량배율']:.2f}배\t{row['당일등락률']:+.2f}%\t{row['종가']}\n"
                
            st.download_button(
                label="📥 특이수급_종목리스트.txt 다운로드",
                data=txt_content,
                file_name="volume_compressed_stocks.txt",
                mime="text/plain"
            )
        else:
            st.warning("최근 1달 내에 해당 조건(거래량 3배↑, 변동률 ±3% 이내)을 만족하는 종목이 없습니다.")


